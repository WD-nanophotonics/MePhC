import importlib.util
import json
from pathlib import Path

import pytest


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "audit/e9f/qp_b_c2_c3_r8_c2_convergence_method_audit.py"
DIAGNOSIS = ROOT / "audit/e9f/qp_b_c2_c3_r8_c2_convergence_diagnosis.json"
CONTRACT = ROOT / "audit/e9f/qp_b_c2_c3_r8_c2_prospective_validation_contract.json"


def load_script():
    spec = importlib.util.spec_from_file_location("_r8_c2_method_audit_test", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope="module")
def analysis():
    module = load_script()
    return module, module.analyze()


def test_exact_srd_and_classification_logic():
    module = load_script()
    assert module.srd(0.0, 0.0) == 0.0
    assert module.srd(1.0, -1.0) == 2.0
    assert module.relation(2.0, 1.0, contraction="C", expansion="E", equality="Q") == "C"
    assert module.relation(2.0, 3.0, contraction="C", expansion="E", equality="Q") == "E"
    assert module.relation(2.0, 2.0, contraction="C", expansion="E", equality="Q") == "Q"


